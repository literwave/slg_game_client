interface Region { polygon: Polygon; left: number; right: number; top: number; bottom: number; }

/** 只判断脚底在建筑轮廓内的深度关系；前景路人不因长枪掠过屋檐就消失。 */
export class CityAmbientOcclusion {
    private readonly regions: Region[];
    constructor(x: number, y: number, polygons?: readonly Polygon[]) {
        this.regions = (polygons || CITY_AMBIENT_OCCLUDERS[`${x},${y}`] || []).map(polygon => ({ polygon,
            left: Math.min(...polygon.map(p => p[0])), right: Math.max(...polygon.map(p => p[0])),
            top: Math.min(...polygon.map(p => p[1])), bottom: Math.max(...polygon.map(p => p[1])),
        }));
    }

    hides(u: number, v: number, wasHidden = false): boolean {
        if (!Number.isFinite(u) || !Number.isFinite(v)) return true;
        const x = u * 1040, y = v * 650, margin = wasHidden ? 3 : 1;
        for (const r of this.regions) {
            if (x < r.left - margin || x > r.right + margin || y < r.top - margin || y > r.bottom + margin) continue;
            let inside = false;
            for (let i = 0, j = r.polygon.length - 1; i < r.polygon.length; j = i++) {
                const a = r.polygon[j], b = r.polygon[i], dx = b[0] - a[0], dy = b[1] - a[1];
                if ((a[1] > y) !== (b[1] > y) && x < (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]) + a[0]) inside = !inside;
                const length2 = dx * dx + dy * dy;
                const t = length2 ? Math.max(0, Math.min(1, ((x - a[0]) * dx + (y - a[1]) * dy) / length2)) : 0;
                const ex = x - a[0] - dx * t, ey = y - a[1] - dy * t;
                if (ex * ex + ey * ey <= margin * margin) return true;
            }
            if (inside) return true;
        }
        return false;
    }
}
