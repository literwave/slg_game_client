export type AmbientPoint = readonly [number, number];
export interface CityAmbientLayout {
    drill: AmbientPoint;
    /** 多组操练各占一块空地，不把所有人排在同一处。 */
    drillYards?: readonly AmbientPoint[];
    trainees: number;
    /** 街区执勤总人数，包含岗哨、固定往返巡逻和随机巡逻。 */
    patrollers: number;
    /** 按路网连通街区分配人数；省略时均分，不按道路长度挤到主街。 */
    patrolDistrictCounts?: readonly number[];
    seed: number;
    /** 原画自带人物的脚底站位，同样要绕行。 */
    standing?: readonly AmbientPoint[];
    /** 相同端点组成路口；不连通的街区不允许抄近路穿楼。 */
    roads: readonly (readonly AmbientPoint[])[];
}
