param([switch]$Check, [switch]$Emit)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
$shapes = [ordered]@{}
$appearanceSource = [IO.File]::ReadAllText((Join-Path $projectRoot 'assets\scripts\map\CityFootprint.ts'))
$regionalArt = [regex]::Matches($appearanceSource, "near: '([^']+)'") | ForEach-Object { $_.Groups[1].Value }
$artNames = @('town-prefecture-v2', 'county-commandery-v4', 'capital-imperial-v2') + @($regionalArt) | Select-Object -Unique
foreach ($art in $artNames) {
    $source = Join-Path $projectRoot ('assets\resources\ui\world\' + $art + '.png')
    $bitmap = [Drawing.Bitmap]::FromFile($source)
    try {
        $columns = 192
        $rowCount = [int][Math]::Ceiling($columns * $bitmap.Height / $bitmap.Width)
        $rows = @()
        for ($y = 0; $y -lt $rowCount; $y++) {
            $row = ''
            for ($group = 0; $group -lt $columns / 4; $group++) {
                $bits = 0
                for ($bit = 0; $bit -lt 4; $bit++) {
                    $x = $group * 4 + $bit
                    $opaque = 0
                    foreach ($sy in @(.25, .5, .75)) {
                        foreach ($sx in @(.25, .5, .75)) {
                            $px = [Math]::Min($bitmap.Width - 1, [int][Math]::Floor(($x + $sx) * $bitmap.Width / $columns))
                            $py = [Math]::Min($bitmap.Height - 1, [int][Math]::Floor(($y + $sy) * $bitmap.Height / $rowCount))
                            if ($bitmap.GetPixel($px, $py).A -ge 48) { $opaque++ }
                        }
                    }
                    if ($opaque -ge 1) { $bits = $bits -bor (1 -shl $bit) }
                }
                $row += $bits.ToString('x')
            }
            $rows += $row
        }
        $shapes[$art] = [ordered]@{ width = $bitmap.Width; height = $bitmap.Height; columns = $columns;
            sourceHash = (Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash.ToLowerInvariant(); rows = $rows }
    } finally { $bitmap.Dispose() }
}
$json = $shapes | ConvertTo-Json -Depth 5
$text = "/** Alpha masks generated by tools/art/build-system-city-hit-masks.ps1. */`nexport const SYSTEM_CITY_SILHOUETTES = $json;`n"
$text = $text.Replace("`r`n", "`n")
$target = Join-Path $projectRoot 'assets\scripts\map\SystemCitySilhouettes.ts'
if ($Emit) {
    Write-Output $text
    return
}
if ($Check) {
    if (!(Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target) -ne $text) {
        throw 'City hit masks do not match the current source images. Regenerate them.'
    }
} else {
    [IO.File]::WriteAllText($target, $text, [Text.UTF8Encoding]::new($false))
}
$shapes.GetEnumerator() | ForEach-Object { [pscustomobject]@{ art = $_.Key; columns = $_.Value.columns; rows = $_.Value.rows.Count } }
